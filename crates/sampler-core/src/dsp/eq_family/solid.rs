use curves::*;

/// `y = b0 x + b1 x1 + b2 x2 - a1 y1 - a2 y2`, the native order.
pub(super) type Coefficients = [f64; 5];
const IDENTITY: Coefficients = [1., 0., 0., 0., 0.];

fn s(table: [f64; N], x: f64) -> f64 {
    Spline::new(table).eval(x)
}

fn normalize(a0: f64, c: [f64; 5]) -> Coefficients {
    let inv = 1. / a0;
    c.map(|v| inv * v)
}

/// Orfanidis peak with prescribed Nyquist gain (G0 = 1), shared tail of 0x141ac4cf0 / 0x141ac4880.
fn orfanidis(w0: f64, gl: f64, gb: f64, dw: f64) -> Coefficients {
    let (g2, gb2) = (gl * gl, gb * gb);
    let e = w0 * w0 - PI * PI;
    let e2 = e * e;
    let (gb2m1, g2m1) = ((gb2 - 1.).abs(), (g2 - 1.).abs());
    let f = 1. / (g2 - gb2).abs();
    let num = g2 * gb2m1 * PI * PI * dw * dw * f + e2;
    let den = PI * gb2m1 * PI * dw * dw * f + e2;
    let g12 = num / den;
    let g1 = g12.sqrt();
    let (d8, d7) = ((g2 - g12).abs(), (gb2 - g12).abs());
    let t = (w0 * 0.5).tan();
    let w2 = (d8 / g2m1).sqrt() * t * t;
    let dwt = ((gb2m1 / d7).sqrt() * w2 + 1.) * (dw * 0.5).tan();
    let two_w2 = w2 + w2;
    let c = dwt * d7 * dwt - ((gb2 - g1).abs() - (d7 * gb2m1).sqrt()) * two_w2;
    let d = ((g2 - g1).abs() - (d8 * g2m1).sqrt()) * two_w2;
    let a = ((d + c) * f).sqrt();
    let b = ((gb2 * d + g2 * c) * f).sqrt();
    let (n, m) = (w2 + g1, w2 + 1.);
    normalize(m + a, [n + b, (g1 - w2) * -2., n - b, (1. - w2) * -2., m - a])
}

fn peak(fs: f64, f: f64, g: f64, q: f64) -> Coefficients {
    if !(f > f64::EPSILON) || !(g.abs() > f64::EPSILON) {
        return IDENTITY;
    }
    let (gl, gb) = (10f64.powf(g * 0.05), 10f64.powf(g * 0.025));
    let w0 = f / fs * (PI * 2.);
    let x = 0.5 / q;
    let dw = (w0.sin() / w0 * ((x * x + 1.).sqrt() + x).ln()).sinh() * (w0 + w0);
    orfanidis(w0, gl, gb, dw)
}

/// 0x141ac4880: the bandwidth refined by six fixed-point steps.
fn peak_iterative(fs: f64, f: f64, g: f64, q: f64) -> Coefficients {
    if !(f > f64::EPSILON) || !(g.abs() > f64::EPSILON) {
        return IDENTITY;
    }
    let (gl, gb) = (10f64.powf(g * 0.05), 10f64.powf(g * 0.025));
    let w0 = f / fs * (PI * 2.);
    let x = 0.5 / q;
    let twice = ((x * x + 1.).sqrt() + x).ln() * 2.;
    let t = (w0 * 0.5).tan();
    let sine = w0.sin();
    let mut v = 2f64.powf(w0 / sine * twice * 0.5);
    let k = 2f64.powf(-twice);
    for _ in 0..6 {
        v *= t;
        v = t / (v.atan() * k).tan();
    }
    let half = (v.ln().sinh() * sine).atan();
    orfanidis(w0, gl, gb, half + half)
}

fn angle(fs: f64, f: f64) -> (f64, f64, f64) {
    let w0 = f / fs * (PI * 2.);
    (w0, w0.sin(), w0.cos())
}

/// RBJ high shelf with slope `slope` (0x141abee60).
fn high_shelf(fs: f64, f: f64, g: f64, slope: f64) -> Coefficients {
    let a = 10f64.powf(g * 0.025);
    if f == 0. {
        return IDENTITY;
    }
    let (_, sin, cos) = angle(fs, f);
    let (am1, ap1) = (a - 1., a + 1.);
    let beta = ((a * a + 1.) / slope - am1 * am1).sqrt() * sin;
    let x5 = am1 * cos;
    let x9 = x5 + ap1;
    let x0 = ap1 * cos;
    let x7 = ap1 - x5;
    let a1 = am1 - x0;
    normalize(x7 + beta, [(beta + x9) * a, (x0 + am1) * a * -2., (x9 - beta) * a, a1 + a1, x7 - beta])
}

/// RBJ low shelf with slope `slope` (0x141ac3480).
fn low_shelf(fs: f64, f: f64, g: f64, slope: f64) -> Coefficients {
    let a = 10f64.powf(g * 0.025);
    if f == 0. {
        return IDENTITY;
    }
    let (_, sin, cos) = angle(fs, f);
    let (am1, ap1) = (a - 1., a + 1.);
    let x7 = am1 * cos;
    let x9 = ap1 - x7;
    let x7 = x7 + ap1;
    let beta = ((a * a + 1.) / slope - am1 * am1).sqrt() * sin;
    let x1 = ap1 * cos;
    let b1 = (a + a) * (am1 - x1);
    normalize(x7 + beta, [(beta + x9) * a, b1, (x9 - beta) * a, am1 * -2. - (x1 + x1), x7 - beta])
}

/// RBJ high/low pass with bandwidth `bw` octaves (0x141abec80 / 0x141ac3300).
fn pass(fs: f64, f: f64, bw: f64, high: bool) -> Coefficients {
    if f == 0. {
        return IDENTITY;
    }
    let (w0, sin, cos) = angle(fs, f);
    let alpha = (bw * 0.34657359027997264 * w0 / sin).sinh() * sin;
    let (b0, b1) = if high { ((cos + 1.) * 0.5, -(cos + 1.)) } else { ((1. - cos) * 0.5, 1. - cos) };
    normalize(alpha + 1., [b0, b1, b0, cos * -2., 1. - alpha])
}

/// Prewarped bilinear first-order high-pass (0x141abedc0).
fn high_pass_1(fs: f64, f: f64) -> Coefficients {
    if f == 0. {
        return IDENTITY;
    }
    let wc = PI * 2. * f;
    let k = wc / (PI * f / fs).tan();
    let inv = 1. / (k + wc);
    let b0 = inv * k;
    [b0, -b0, 0., (wc - k) * inv, 0.]
}

/// How many biquads the section of `kind` contributes.
pub(super) fn sections(which: SolidSection, kind: Kind) -> usize {
    match (which, kind) {
        (SolidSection::LowFrequency, Kind::LowShelf) => 3,
        (SolidSection::HighFrequency, Kind::HighShelf) | (SolidSection::HighPass, _) | (SolidSection::LowPass, _) => 2,
        _ => 1,
    }
}

/// Biquad `index` of `which` for the saved knobs (each 0..=1). `kind` is Peak for the LF/HF
/// bell, LowShelf/HighShelf for their shelves.
pub(super) fn coefficients(
    which: SolidSection,
    kind: Kind,
    index: usize,
    rate: f64,
    frequency: f64,
    q: f64,
    gain: f64,
) -> Coefficients {
    let (f, qk, g) = (frequency.clamp(0., 1.), q.clamp(0., 1.), gain.clamp(0., 1.));
    let high = rate >= 60000.;
    match (which, kind, index) {
        (SolidSection::HighFrequency, Kind::HighShelf, 0) => {
            high_shelf(rate, s(C_6568, g) * s(C_6138, f), s(C_5D08, g), 0.55000000000000004)
        }
        (SolidSection::HighFrequency, Kind::HighShelf, _) => {
            peak(rate, s(C_6BB0, f), s(C_6998, g), 0.69999999999999996)
        }
        (SolidSection::HighFrequency, ..) => peak(
            rate,
            s(C_58D8, g) * s(FREQ_HF, f),
            s(C_54A8, f) * s(GAIN_HF, g),
            s(C_4818, g) * 1.2 * s(if high { C_4C48 } else { C_5078 }, f),
        ),
        (SolidSection::HighMid, ..) => {
            let (hz, db) = (s(C_7E88, g) * s(FREQ_HMF, f), s(C_7628, f) * s(GAIN_HMF, g) * s(C_7A58, qk));
            if high {
                peak(rate, hz, db, s(C_71F8, g) * s(Q_HMF, qk))
            } else {
                peak_iterative(rate, hz, db, s(C_6DC8, qk) * s(C_71F8, g))
            }
        }
        (SolidSection::LowMid, ..) => peak(
            rate,
            s(C_8F48, g) * s(FREQ_LMF, f),
            s(C_86E8, f) * s(GAIN_LMF, g) * s(C_8B18, qk),
            s(C_82B8, g) * s(Q_LMF, qk),
        ),
        (SolidSection::LowFrequency, Kind::LowShelf, 0) => {
            low_shelf(rate, s(C_A868, g) * s(C_A438, f), s(C_A008, g) * s(C_AC98, f), 0.5)
        }
        (SolidSection::LowFrequency, Kind::LowShelf, 1) => {
            peak(rate, s(C_B2E0, f), s(C_B0C8, g) * s(C_B4F8, f), 0.5)
        }
        (SolidSection::LowFrequency, Kind::LowShelf, _) => {
            peak(rate, s(C_B928, f), s(C_B710, g) * s(C_BB40, f), 0.5)
        }
        (SolidSection::LowFrequency, ..) => peak(
            rate,
            (1. - (1. - s(C_9BD8, g)) * 0.5 * f) * s(FREQ_LF, f),
            s(C_97A8, f) * s(GAIN_LF, g),
            s(C_9378, g) * 1.0800000000000001,
        ),
        (SolidSection::HighPass, _, 0) => pass(rate, s(FREQ_HP, f), s(C_BD58, f), true),
        (SolidSection::HighPass, ..) => high_pass_1(rate, s(FREQ_HP, f)),
        (SolidSection::LowPass, _, index) => {
            // Shelf Hz, dB, slope; then the second section's Hz, dB (or bandwidth), Q.
            let [sf, sg, ss, pf, pg, pq] = if rate < 46000. {
                [C_C3A0, C_C188, C_C5B8, C_C9E8, C_C7D0, C_CC00]
            } else if rate < 60000. {
                [C_D030, C_CE18, C_D248, C_D678, C_D460, C_D890]
            } else if rate < 120000. {
                [C_DCC0, C_DAA8, C_DED8, C_E0F0, C_E308, C_E308]
            } else {
                [C_E738, C_E520, C_E950, C_EB68, C_ED80, C_ED80]
            };
            match (index, high) {
                (0, _) => high_shelf(rate, s(sf, f), s(sg, f), s(ss, f)),
                (_, false) => peak(rate, s(pf, f), s(pg, f), s(pq, f)),
                (_, true) => pass(rate, s(pf, f), s(pg, f), false),
            }
        }
    }
}

