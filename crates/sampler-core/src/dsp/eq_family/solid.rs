//! Solid G-EQ (`BEffectSSLGEQ`, core `NI::DSP::CSL::G_EQ`): the native coefficient law.
//!
//! Splines: eleven-knot cubic splines on the grid D(F(i*F(.1))) with zero slope at the left and a
//! natural right end, initializer 0x141a9a510, evaluators 0x141a98340 (slot, clamped) and
//! 0x141a95be0 (curve). All 104 tables are static data built by the core constructor 0x141a800c0
//! (`C_xxxx` = the curve's offset in the core). PROVED against original instructions (the
//! KONTAKT_DSP_LAWS vectors and Unicorn runs of setter 0x141ac70f0 and process 0x141aaa620).
//!
//! Topology (PROVED): a serial cascade of f64 direct-form-I biquads, f32 in and out, one
//! coefficient set for every channel. Saved field -> core index (reader 0x140d029f0, apply
//! 0x1409619b0): LF 9..11, LMF 6..8, HMF 3..5, HF 0..2, HP 12, LP 13, LP on 15, HP on 14. Bank 0
//! applies (core parameter 0x20 is never raised; the Kontakt measurement agrees). Each section
//! uses only its own knobs:
//! - HF bell: one peak. HF shelf: RBJ high shelf (S 0.55) plus a peak (Q 0.7).
//! - HMF: one peak (below 60 kHz the iterative-bandwidth peak 0x141ac4880). LMF, LF bell: a peak.
//! - LF shelf: RBJ low shelf (S 0.5) plus two peaks (Q 0.5).
//! - HP: RBJ high-pass (bandwidth form) plus a prewarped first-order high-pass (18 dB/oct).
//! - LP: an RBJ high-shelf cut plus a peak (below 60 kHz) or an RBJ low-pass (12 dB/oct), from
//!   one of four table sets chosen by rate (46, 60, 120 kHz).
//! Peaks are Orfanidis designs with a prescribed Nyquist gain (0x141ac4cf0). OPEN: coefficient
//! smoothing (Kontakt builds the core with smoothing on: 20 ms in whole blocks, update
//! 0x141ab4d70); here coefficients switch at the band stage's control rate.
use sampler_ir::fx::eq::{Kind, SolidSection};
use std::f64::consts::PI;

const N: usize = 11;

/// The native grid: F(i * F(0.1)) widened, so it is not exact decimal tenths.
fn grid() -> [f64; N] {
    let tenth = 0.1_f32;
    std::array::from_fn(|i| f64::from(i as f32 * tenth))
}

#[derive(Clone, Copy)]
pub(crate) struct Spline {
    x: [f64; N],
    y: [f64; N],
    m: [f64; N],
}

impl Spline {
    /// Second derivatives for a spline with zero slope at the left end and zero second
    /// derivative at the right (the checked boundary controls 11 and 1e32).
    pub(crate) fn new(y: [f64; N]) -> Self {
        let x = grid();
        let (mut m, mut u) = ([0.; N], [0.; N]);
        m[0] = -0.5;
        u[0] = 3. / (x[1] - x[0]) * ((y[1] - y[0]) / (x[1] - x[0]));
        for i in 1..N - 1 {
            let sig = (x[i] - x[i - 1]) / (x[i + 1] - x[i - 1]);
            let p = sig * m[i - 1] + 2.;
            m[i] = (sig - 1.) / p;
            let d = (y[i + 1] - y[i]) / (x[i + 1] - x[i]) - (y[i] - y[i - 1]) / (x[i] - x[i - 1]);
            u[i] = (6. * d / (x[i + 1] - x[i - 1]) - sig * u[i - 1]) / p;
        }
        m[N - 1] = 0.;
        for k in (0..N - 1).rev() {
            m[k] = m[k] * m[k + 1] + u[k];
        }
        Self { x, y, m }
    }

    /// Evaluate at `u`, clamped to the grid's ends.
    pub(crate) fn eval(&self, u: f64) -> f64 {
        let u = if u.is_nan() { 0. } else { u.clamp(self.x[0], self.x[N - 1]) };
        let i = (0..N - 1).rev().find(|&i| u >= self.x[i]).unwrap_or(0);
        let h = self.x[i + 1] - self.x[i];
        let (a, b) = ((self.x[i + 1] - u) / h, (u - self.x[i]) / h);
        a * self.y[i]
            + b * self.y[i + 1]
            + ((a * a * a - a) * self.m[i] + (b * b * b - b) * self.m[i + 1]) * h * h / 6.
    }
}

