/// `x` (held within ±1) through `curve`, linearly between its points.
fn read(curve: &[f32; POINTS], x: f32) -> f32 {
    let at = (x.clamp(-1.0, 1.0) + 1.0) * 0.5 * (POINTS - 1) as f32;
    let i = (at as usize).min(POINTS - 2);
    let (a, b) = (
        curve.get(i).copied().unwrap_or(0.0),
        curve.get(i + 1).copied().unwrap_or(0.0),
    );
    a + (b - a) * (at - i as f32)
}

/// The curves either side of `drive` (0..=1) and how far along:
/// `(lower, upper, t)`, `None` standing for DRIVE 0 (the input itself).
pub(crate) fn between(drive: f32) -> (Option<&'static [f32; POINTS]>, &'static [f32; POINTS], f32) {
    let at = drive.clamp(0.0, 1.0) * 4.0;
    let [c25, c50, c75, c100] = &CURVES;
    match at {
        ..=1.0 => (None, c25, at),
        ..=2.0 => (Some(c25), c50, at - 1.0),
        ..=3.0 => (Some(c50), c75, at - 2.0),
        _ => (Some(c75), c100, at - 3.0),
    }
}

/// `x` through the Tube curve at `(lower, upper, t)` from [`between`].
pub(crate) fn tube(x: f32, lower: Option<&[f32; POINTS]>, upper: &[f32; POINTS], t: f32) -> f32 {
    let a = lower.map_or(x, |c| read(c, x));
    a + (read(upper, x) - a) * t
}
