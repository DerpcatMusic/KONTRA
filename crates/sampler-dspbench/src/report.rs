//! Markdown, JSON and CSV output. The markdown holds the verdict table and per-rate detail; the CSV
//! has the full grid (pair x implementation x rate x block) for plotting.

use crate::pairs::{PairReport, Side};
use std::fmt::Write;

fn fmt(v: f64) -> String {
    if v.is_finite() { format!("{v:.1}") } else { "n/a".into() }
}

pub fn markdown(reports: &[PairReport], band: &crate::band::Band, machine: &str) -> String {
    let mut s = String::new();
    writeln!(s, "# DSP bake-off: ours vs candidates\n").ok();
    writeln!(s, "Machine: {machine}. Generated by `dspbench`; reproduce with `build-slot cargo run -p sampler-dspbench --features candidates --release`.\n").ok();
    writeln!(s, "Tolerance bands: magnitude shape +-{} dB, phase +-{} deg, time constants +-{} %, \"cleaner\" = {} dB on aliasing or noise (or stability / subnormal win).\n", band.mag_db, band.phase_deg, band.time_pct, band.cleaner_margin_db).ok();
    writeln!(s, "## Verdicts (48 kHz, 64-frame blocks)\n").ok();
    writeln!(s, "| Pair | Implementation | Fidelity: worst shape (dB) | Alias (dB) | THD+N (dB) | Noise (dBFS) | Subnormal | Stable | Latency | ns/frame | instr/frame | Verdict |").ok();
    writeln!(s, "|---|---|---|---|---|---|---|---|---|---|---|---|").ok();
    for r in reports.iter().filter(|r| (r.rate - 48000.0).abs() < 0.5 && (r.block == 64 || r.block == 0)) {
        for side in &r.sides {
            writeln!(s, "{}", row(r, side)).ok();
        }
    }
    writeln!(s, "\n## Notes\n").ok();
    for r in reports.iter().filter(|r| (r.rate - 48000.0).abs() < 0.5 && (r.block == 64 || r.block == 0)) {
        writeln!(s, "- **{}**: reference: {}.", r.title, r.reference).ok();
        for side in &r.sides {
            writeln!(s, "  - {}: {}", side.label, side.note).ok();
        }
    }
    s
}

fn row(r: &PairReport, side: &Side) -> String {
    let q = &side.quality;
    let fid = side.fit.map_or("n/a".into(), |f| fmt(f.mag_err_db));
    let instr = q.instr_per_frame.map_or("n/a".into(), |v| format!("{v:.0}"));
    format!(
        "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {:.2} | {} | {} |",
        r.title,
        side.label,
        fid,
        fmt(q.alias_db),
        fmt(q.thd_n_db),
        fmt(q.noise_dbfs),
        q.subnormal,
        if q.stable { "yes" } else { "NO" },
        q.latency,
        q.ns_per_frame,
        instr,
        side.verdict.label(),
    )
}

pub fn csv(reports: &[PairReport]) -> String {
    let mut s = String::from("pair,implementation,rate,block,fidelity_worst_db,fidelity_median_db,alias_db,thd_n_db,noise_dbfs,subnormal,denormal_spike,stable,peak_dbfs,latency,ns_per_frame,instr_per_frame,verdict\n");
    for r in reports {
        for side in &r.sides {
            let q = &side.quality;
            let (w, m) = side.fit.map_or((f64::NAN, f64::NAN), |f| (f.mag_err_db, f.mag_err_median_db));
            writeln!(
                s,
                "{},{},{},{},{:.3},{:.3},{:.2},{:.2},{:.2},{},{:.2},{},{:.2},{},{:.3},{},{}",
                r.id,
                side.label,
                r.rate,
                r.block,
                w,
                m,
                q.alias_db,
                q.thd_n_db,
                q.noise_dbfs,
                q.subnormal,
                q.denormal_spike,
                q.stable,
                q.peak_dbfs,
                q.latency,
                q.ns_per_frame,
                q.instr_per_frame.map_or(String::new(), |v| format!("{v:.1}")),
                side.verdict.label(),
            )
            .ok();
        }
    }
    s
}
