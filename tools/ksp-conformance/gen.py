#!/usr/bin/env python3
"""KSP conformance generator and golden decoder.

    tools/ksp-conformance/gen.py gen               write cases/*.ksp, manifest.json, generated/batch_*.lua
    tools/ksp-conformance/gen.py decode OUT.jsonl...  turn Kontakt oracle batch logs into golden.json

`gen` is pure text: the same .ksp source goes to Kontakt (through a generated probe, one
batch of at most 16 cases per oracle session) and to the KONTRA interpreter (the
sampler-ksp conformance test reads cases/*.ksp). `decode` reads the bit strings the probe
logged and writes the expected 32-bit results to golden.json.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cases as C  # noqa: E402

BATCH = 16
MAX_RESULTS = 2  # 32 groups per result; keep one instrument under 64 groups


# Marker groups: START is written first in on init, END last. A unit whose START group does
# not read back did not compile (Kontakt drops the whole script silently); a missing END means
# init aborted part-way. Results sit in groups 0..63, markers at 64 and 65.
START, END = 64, 65
MARK = "  set_engine_par($ENGINE_PAR_VOLUME, 1000, {g}, -1, -1)\n"


def source_of(case):
    _, _, setup, results, top = case
    body = C.DECLS + MARK.format(g=START)
    body += "".join(f"  {line.strip()}\n" for line in setup.split("\n") if line.strip())
    for k, expr in enumerate(results):
        body += C.ENCODER.format(expr=expr, base=32 * k)
    body += MARK.format(g=END)
    head = top + "\n" if top else ""
    return f"{head}on init\n{body}end on\n"


def units():
    """Cases split so each unit has at most MAX_RESULTS results (one instrument each)."""
    out = []
    for case in C.CASES:
        cid, cat, setup, results = case[:4]
        top = case[4] if len(case) > 4 else ""
        chunks = [results[i:i + MAX_RESULTS] for i in range(0, len(results), MAX_RESULTS)]
        for n, chunk in enumerate(chunks):
            uid = cid if len(chunks) == 1 else f"{cid}__{n}"
            out.append((uid, cat, setup, chunk, top))
    if len({u[0] for u in out}) != len(out):
        raise SystemExit("duplicate case id")
    return out


def lua_batch(batch):
    lines = [
        "-- GENERATED by tools/ksp-conformance/gen.py; do not edit.",
        "-- One oracle session: each case is one instrument, 32 groups per result.",
        "local kt = Kontakt",
        "local out = assert(io.open(ORACLE_OUT, \"w\"))",
        "local function log(t) out:write(t .. \"\\n\") out:flush() end",
        "kt.reset_multi()",
        "local CASES = {",
    ]
    for case in batch:
        n = len(case[3])
        lines.append(
            f'  {{ id = "{case[0]}", results = {n}, src = [==[\n{source_of(case)}]==] }},'
        )
    lines += [
        "}",
        "local ids = {}",
        "for n, c in ipairs(CASES) do",
        "  local i = kt.add_instrument()",
        "  kt.set_instrument_volume(i, 0)",
        "  for _ = 1, 65 do kt.add_group(i) end",
        "  ids[n] = i",
        "  local ok, err = pcall(kt.set_instrument_script_source, i, 0, c.src)",
        "  log(string.format('{\"compile\":\"%s\",\"ok\":%s}', c.id, tostring(ok)))",
        "  if not ok then log(string.format('{\"error\":\"%s\"}', tostring(err):gsub('\"', \"'\"))) end",
        "end",
        "local t0 = os.time()",
        "repeat until os.time() - t0 >= 4",
        "for n, c in ipairs(CASES) do",
        "  local rows = {}",
        f"  local start = kt.get_group_volume(ids[n], {START}) < -100",
        f"  local finish = kt.get_group_volume(ids[n], {END}) < -100",
        "  for k = 0, c.results - 1 do",
        "    local bits = {}",
        "    for b = 0, 31 do",
        "      local db = kt.get_group_volume(ids[n], 32 * k + b)",
        "      bits[#bits + 1] = (db < -100) and '1' or '0'",
        "    end",
        "    rows[#rows + 1] = '\"' .. table.concat(bits) .. '\"'",
        "  end",
        "  log(string.format('{\"case\":\"%s\",\"start\":%s,\"end\":%s,\"bits\":[%s]}', c.id, tostring(start), tostring(finish), table.concat(rows, ',')))",
        "end",
        "log('{\"done\":true}')",
        "out:close()",
        "",
    ]
    return "\n".join(lines)


def gen():
    all_units = units()
    (HERE / "cases").mkdir(exist_ok=True)
    (HERE / "generated").mkdir(exist_ok=True)
    manifest = []
    for old in (HERE / "cases").glob("*.ksp"):
        old.unlink()
    for case in all_units:
        (HERE / "cases" / f"{case[0]}.ksp").write_text(source_of(case))
        manifest.append({"id": case[0], "category": case[1], "results": len(case[3])})
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
    for old in (HERE / "generated").glob("batch_*.lua"):
        old.unlink()
    for n, start in enumerate(range(0, len(all_units), BATCH)):
        batch = all_units[start:start + BATCH]
        (HERE / "generated" / f"batch_{n:02d}.lua").write_text(lua_batch(batch))
    print(f"{len(C.CASES)} cases, {len(all_units)} units, {(len(all_units) + BATCH - 1) // BATCH} oracle batches")


def to_signed(bits):
    value = int(bits[::-1], 2)  # bit 0 is the first character
    return value - (1 << 32) if value >= 1 << 31 else value


def decode(paths):
    # Merge into the committed golden: a batch run only refreshes the cases it contains.
    out = HERE / "golden.json"
    golden = json.loads(out.read_text()) if out.exists() else {}
    compile_errors = []
    lines = [line for path in paths for line in Path(path).read_text().splitlines()]
    for line in lines:
        if not line.startswith("{"):
            continue
        row = json.loads(line) if '"bits"' in line else None
        if row is None:
            if '"ok":false' in line or '"error"' in line:
                compile_errors.append(line)
            continue
        golden[row["case"]] = {
            "compiled": row["start"],
            "completed": row["end"],
            "results": [to_signed(b) for b in row["bits"]],
        }
    expected = {u[0] for u in units()}
    missing = sorted(expected - set(golden))
    out.write_text(json.dumps(golden, indent=1, sort_keys=True) + "\n")
    print(f"{len(golden)} golden cases -> {out}")
    if missing:
        print("missing:", ", ".join(missing))
    for e in compile_errors:
        print("oracle:", e)


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "gen":
        gen()
    elif len(sys.argv) >= 3 and sys.argv[1] == "decode":
        decode(sys.argv[2:])
    else:
        print(__doc__)
        sys.exit(2)
