#!/usr/bin/env python3
"""Generate Rust constants for one decompiled Kontakt 8 DSP function group from the PE image.

    gen_amp_consts.py Kontakt8.exe OUT.rs PAIR_TABLE_VA PAIR_COUNT DECOMP.c [DECOMP.c ...]

Every global the decompile names (`DAT_<va>`, `_DAT_<va>`, `fRam0000000<va>`) becomes a
`C_<VA>: f32 = f32::from_bits(..)` constant, read from the image's data. The (offset, slope)
pair table at PAIR_TABLE_VA is emitted as `PAIRS`, entry k = (float at VA + 8k, float at VA + 8k + 4),
as the decompile indexes it: `(&DAT_<va+4>)[k*2]` and `(&DAT_<va>)[k*2]`.
"""
import re
import struct
import sys

import pefile

NAME = re.compile(r"\b(?:_?DAT_|fRam0000000)([0-9a-f]{6,})\b")


def main():
    exe, out, pair_va, pair_n, *sources = sys.argv[1:]
    pe = pefile.PE(exe, fast_load=True)
    data = pe.__data__
    base = pe.OPTIONAL_HEADER.ImageBase

    def read(va, n):
        return data[pe.get_offset_from_rva(va - base): pe.get_offset_from_rva(va - base) + n]

    addrs = set()
    for path in sources:
        with open(path, encoding="utf-8", errors="replace") as f:
            for m in NAME.finditer(f.read()):
                addrs.add(int(m.group(1), 16))
    pair_va, pair_n = int(pair_va, 16), int(pair_n)
    pair_bytes = set(range(pair_va, pair_va + 8 * pair_n))
    lines = [
        "//! Generated by tools/kontakt-oracle/gen_amp_consts.py from the Kontakt 8 image. Do not edit.",
        "//! Each constant is the single-precision value at the image address in its name.",
        "#![allow(clippy::unreadable_literal, dead_code)]",
        "",
    ]
    for va in sorted(addrs):
        if va in pair_bytes:
            continue
        bits = struct.unpack("<I", read(va, 4))[0]
        lines.append(f"pub(crate) const C_{va:X}: f32 = f32::from_bits(0x{bits:08x}); // {va:#x}")
    pairs = []
    for k in range(pair_n):
        off = struct.unpack("<I", read(pair_va + 8 * k, 4))[0]
        slope = struct.unpack("<I", read(pair_va + 8 * k + 4, 4))[0]
        pairs.append(f"(f32::from_bits(0x{off:08x}), f32::from_bits(0x{slope:08x}))")
    lines += ["", f"/// Piecewise pair table at {pair_va:#x}: (intercept, slope) per index.",
              f"pub(crate) const PAIRS: [(f32, f32); {pair_n}] = ["]
    lines += [f"    {p}," for p in pairs]
    lines.append("];")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(out, "scalars", len(addrs) - len(pair_bytes & {a for a in addrs}), "pairs", pair_n)


if __name__ == "__main__":
    main()
