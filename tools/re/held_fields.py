#!/usr/bin/env python3
"""held_fields.py > crates/format/kontakt/data/held_fields.tsv

Where each effect module saves the controls a script reads back: module id,
saved version, KSP name, byte offset in the module's saved record, kind
(F float 0..1 read as value/1e6, I index, B switch, U a tempo unit: the
field holding beats per `$NI_SYNC_UNIT_*`, −1 when the time runs free). Joins the measured
bindings (docs/re/kontakt-bindings/fx_*.tsv: field index, kind, law) with
the readers' layouts (docs/architecture-v2/KONTAKT_FX_MOD_READERS.tsv: the
primitive each field reads, in order; F and I 4 bytes, B 1). A field
whose kind disagrees with its layout is left out, and so is any law but
identity, a switch or an index table, whose saved value is not the
script's value as it is.
"""
import glob
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SIZE = {"F": 4, "I": 4, "B": 1}

# Replika has no reader row: replika.rs's measured offsets.
REPLIKA = (0x5A, 0x12, "IFFFFFFFFFFBBBFF", {26: 89, 27: 93, 28: 97, 32: 113})

layouts = {}
for line in (ROOT / "docs/architecture-v2/KONTAKT_FX_MOD_READERS.tsv").read_text().splitlines()[1:]:
    cls, mid, ver, _, _, layout = line.split("\t")[:6]
    layouts[cls.removeprefix("struct ")] = (int(mid, 16), int(ver, 16), layout, {})
layouts["BParFXReplikaDelay"] = REPLIKA


def offset(layout, pinned, field):
    if field in pinned:
        return pinned[field]
    if field >= len(layout):
        return None
    return sum(SIZE[c] for c in layout[:field])


def plain(kind, law, points):
    if kind == "F":
        return law == "identity"
    if kind == "B":
        return law.startswith("bool: stored=1 when value>=1")
    # An index table: each value stored as itself.
    return law == "table" and all(a == b for a, b in (p.split(":") for p in points.split()))


# A unit's beats field: units 0..4 save −1, 5 four beats, 6 two and two thirds.
BEATS = re.compile(r"^0:-1 1:-1 2:-1 3:-1 4:-1 5:4 6:2\.66")

rows, names, units = [], {}, []
for path in sorted(glob.glob(str(ROOT / "docs/re/kontakt-bindings/fx_*.tsv"))):
    for line in pathlib.Path(path).read_text().splitlines()[1:]:
        f = line.split("\t")
        if len(f) < 10 or not f[1].startswith("$ENGINE_PAR_") or f[2] not in layouts:
            continue
        par, cls, ver, field, kind, law, points = f[1], f[2], int(f[3], 16), int(f[4]), f[6], f[7], f[9]
        names.setdefault(par, []).append(cls)
        mid, lver, layout, pinned = layouts[cls]
        at = offset(layout, pinned, field)
        known = field in pinned or (field < len(layout) and layout[field] == kind)
        if ver != lver or at is None or not known:
            continue
        if plain(kind, law, points):
            rows.append((mid, ver, par, at, kind))
        elif kind == "F" and BEATS.match(points):
            units.append((mid, ver, par, at, "U"))

# A name bound to several fields (a unit) is not one saved value.
rows = [r for r in rows if len(names[r[2]]) == 1] + units
print("# Generated by tools/re/held_fields.py; see its docstring.")
print("# module\tversion\tname\toffset\tkind")
for mid, ver, par, at, kind in sorted(set(rows)):
    print(f"{mid:#04x}\t{ver:#04x}\t{par}\t{at}\t{kind}")
print(f"# {len(set(rows))} fields", file=sys.stderr)
