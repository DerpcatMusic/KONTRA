#!/usr/bin/env python3
"""Generate ni-file's effect parameter layouts from Kontakt's own readers.

    tools/re/gen_fx_layouts.py docs/re/kontakt-catalog/reader_schemas.tsv \
        > vendor/ni-file/src/kontakt/objects/native_fx_layouts.rs

Only BParFX* classes whose layout for a version is fully typed (no `?`, nested
object, string or list) are emitted; anything else stays with the hand reader
and is listed in the generated file's header, so a gap is visible.
"""
import csv
import sys

TYPE = {"F": "f", "B": "b", "I": "i", "E": "i", "H": "h", "X": "fffb"}

rows = [r for r in csv.DictReader(open(sys.argv[1]), delimiter="\t")
        if r["class"].startswith("struct BParFX") and r["class"] != "struct BParFX"
        and r["stored_version"] not in ("-", "")]
emit, skipped = {}, []
for r in rows:
    key = (int(r["sertype"], 16), int(r["stored_version"], 16))
    lay = r["layout"]
    if not lay or any(c not in TYPE for c in lay):
        skipped.append(f"{r['class'][7:]} 0x{key[0]:02X} v0x{key[1]:X}: {lay}")
        continue
    emit[key] = ("".join(TYPE[c] for c in lay), r["class"][7:], r["reader_va"])

out = sys.stdout
out.write("""// @generated by tools/re/gen_fx_layouts.py from Kontakt 8.13.1's own readers
// (docs/re/kontakt-catalog/reader_schemas.tsv). Do not edit by hand.
//
// Each layout is the native read order for one (SerType, stored version):
// f = 4-byte float, i = u32 (enums are validated u32), b = u8, h = u16.
""")
for s in sorted(skipped):
    out.write(f"// not generated (untyped reads): {s}\n")
out.write("\n/// Native field layout for an effect's stored parameters, if fully typed.\n")
out.write("pub fn native_fx_layout(module: u16, version: u16) -> Option<&'static str> {\n")
out.write("    Some(match (module, version) {\n")
for (m, v), (lay, cls, va) in sorted(emit.items()):
    out.write(f"        (0x{m:02X}, 0x{v:X}) => \"{lay}\", // {cls} {va}\n")
out.write("        _ => return None,\n    })\n}\n")
print(f"{len(emit)} layouts, {len(skipped)} skipped", file=sys.stderr)
