#!/usr/bin/env python3
"""Generate ni-file's native reader schemas from Kontakt 8.13.1's own readers.

    tools/re/gen_native_schemas.py docs/re/kontakt-catalog/ser_classes.tsv decompiled.c \
        vendor/ni-file/src/kontakt/native_schema/programs.rs \
        vendor/ni-file/tests/native_schema_samples.txt \
        docs/re/kontakt-catalog/reader_schemas.tsv

programs.rs holds the lowered readers (reader_lower.py IR) and, per SerType, the stored
versions Kontakt accepts. The samples file holds streams Kontakt's readers accept
(found by reader_schemas.py's search), with the read sequence the reference interpreter
produced, so the Rust executor is checked against an independent implementation.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import reader_schemas as rs  # noqa: E402


def ranges(vs):
    out = []
    for v in sorted(vs):
        if out and out[-1][1] + 1 == v:
            out[-1][1] = v
        else:
            out.append([v, v])
    return out


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    classes, decompiled, rust_out, samples_out, tsv_out = sys.argv[1:6]
    rows, progs, readers = rs.load(classes, decompiled)
    res = rs.analyze_final(rows, progs, readers)

    # Programs reachable from a reader.
    import re
    keep, todo = set(), ["FUN_" + r["reader_va"][2:] for r in rows]
    while todo:
        n = todo.pop()
        if n in keep or n not in progs:
            continue
        keep.add(n)
        for op in progs[n]["ops"]:
            m = re.match(r"\(call (\w+) ", op)
            if m:
                todo.append(m.group(1))

    out = ["""// @generated by tools/re/gen_native_schemas.py from Kontakt 8.13.1's own readers
// (docs/re/kontakt-catalog/reader_schemas.tsv). Do not edit by hand.
//
// PROGRAMS: each serializable class's versioned reader and the helpers it calls, lowered to
// the stream IR documented in tools/re/reader_lower.py. READERS: per SerType and class, the
// stored versions the reader accepts (inclusive ranges) and how completely they decode.

pub(super) struct ProgramSrc {
    pub name: &'static str,
    pub params: &'static [&'static str],
    pub frame: u32,
    pub ops: &'static str,
}

pub(super) struct ReaderSrc {
    pub sertype: u16,
    pub class: &'static str,
    pub program: &'static str,
    pub current: u16,
    pub versions: &'static [(u16, u16)],
    /// SerType of the objects a container embeds (array elements), 0 if none.
    pub element: u16,
    /// "typed", "host-branch", "nested", "virtual:..", "stub", "not-a-reader"
    pub status: &'static str,
}

pub(super) static PROGRAMS: &[ProgramSrc] = &["""]
    for n in sorted(keep):
        p = progs[n]
        params = ", ".join(f'"{x}"' for x in p["params"])
        body = "\n".join(p["ops"])
        out.append(f'    ProgramSrc {{ name: "{n}", params: &[{params}], frame: {p["frame"]}, ops: "\\\n{esc(body)}" }},')
    out.append("];\n\npub(super) static READERS: &[ReaderSrc] = &[")
    seen = set()
    for r in rows:
        n = "FUN_" + r["reader_va"][2:]
        cls = r["class"].split(" ", 1)[1]
        key = (r["sertype"], cls)
        if key in seen:
            continue
        seen.add(key)
        info = res[n]
        vs = ranges(info["versions"])
        statuses = sorted({i["status"] for i in info["versions"].values()})
        if info["stub"]:
            status = "not-a-reader" if info.get("not_reader") else "stub"
        elif not vs:
            status = "no-version-accepted"
        else:
            order = ["typed", "host-branch", "nested"]
            status = max(statuses, key=lambda s: (s.startswith("virtual"), order.index(s) if s in order else -1))
        versions = ", ".join(f"({a}, {b})" for a, b in vs)
        elem = rs.ELEMENT_CLASS.get(int(r["sertype"], 16), 0)
        prog = n if n in keep and not info["stub"] else ""
        out.append(f'    ReaderSrc {{ sertype: {int(r["sertype"], 16)}, class: "{esc(cls)}", program: "{prog}", '
                   f'current: {int(r["version"], 16)}, versions: &[{versions}], element: {elem}, status: "{esc(status)}" }},')
    out.append("];")
    Path(rust_out).write_text("\n".join(out) + "\n")

    lines = ["# sertype version kinds hex  (@generated by tools/re/gen_native_schemas.py)"]
    for r in rows:
        n = "FUN_" + r["reader_va"][2:]
        for v, i in res[n]["versions"].items():
            for _, data, kinds in i["samples"]:
                lines.append(f'{int(r["sertype"], 16)} {v} {kinds} {data.hex() or "-"}')
    # a (sertype, version) pair shared by two classes with one reader would repeat; keep first
    uniq = list(dict.fromkeys(lines))
    Path(samples_out).write_text("\n".join(uniq) + "\n")

    with open(tsv_out, "w") as f:
        f.write("class\tsertype\tnative_version\tstored_version\tlayout\tstatus\treader_va\n")
        for r in rows:
            n = "FUN_" + r["reader_va"][2:]
            info = res[n]
            head = f"{r['class']}\t{r['sertype']}\t{r['version']}"
            if info["stub"] or not info["versions"]:
                why = ("not-a-reader" if info.get("not_reader") else "stub") if info["stub"] else "no-version-accepted"
                f.write(f"{head}\t-\t\t{why}\t{r['reader_va']}\n")
                continue
            for v, i in info["versions"].items():
                f.write(f"{head}\t0x{v:X}\t{i['layout']}\t{i['status']}\t{r['reader_va']}\n")
    print(len(keep), "programs,", len(uniq) - 1, "samples", file=sys.stderr)


if __name__ == "__main__":
    main()
