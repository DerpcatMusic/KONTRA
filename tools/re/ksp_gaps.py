#!/usr/bin/env python3
"""Rank KSP symbols by corpus usage x verification gap and write docs/re/KSP_GAPS.md.

    python3 tools/re/ksp_gaps.py [--top N]

Input: docs/re/ksp/SYMBOLS.tsv (run `tools/re/ksp_symbols.py sync` first).
A symbol is a gap when its ledger status is not `full`, or when no test names it
(`tests` column empty), or when no real-Kontakt measurement backs it (`oracle` column,
see docs/re/KSP_GAPS.md "Oracle evidence"). Score = corpus count x (1 + gap weights).
Only rows with a corpus count are listed; the table is the work queue, top to bottom.
"""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SYMBOLS = ROOT / "docs/re/ksp/SYMBOLS.tsv"
OUT = ROOT / "docs/re/KSP_SYMBOL_GAPS.md"

# Real-Kontakt evidence recorded so far. Keep in sync with docs/re/KSP_GAPS.md.
ORACLE = {}


def count(value):
    head = (value or "").split(" ", 1)[0]
    return int(head) if head.isdigit() else 0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--top", type=int, default=80)
    args = parser.parse_args()
    rows = []
    with SYMBOLS.open(newline="") as f:
        for row in csv.DictReader(f, delimiter="\t"):
            corpus = count(row["corpus"])
            if corpus == 0 or row["class"] != "compat":
                continue
            tested = count(row["tests"]) > 0
            full = row["status"] == "full"
            oracle = row["name"] in ORACLE
            weight = 1 + (0 if full else 1) + (0 if tested else 1) + (0 if oracle else 1)
            rows.append((corpus * weight, corpus, row, tested, full, oracle))
    rows.sort(key=lambda r: (-r[0], -r[1], r[2]["name"]))
    lines = [
        "# KSP symbol gap queue (generated)",
        "",
        "Generated by `tools/re/ksp_gaps.py` from `docs/re/ksp/SYMBOLS.tsv`. Do not edit by hand.",
        "",
        "Score = corpus instruments using the symbol x (1 + not-full + untested + no oracle evidence).",
        "Higher is first. `oracle` lists real-Kontakt measurements recorded in this file's",
        "\"Oracle evidence\" section; none are recorded yet unless listed there.",
        "",
        "| # | symbol | category | status | tests | corpus | oracle | owner |",
        "|---:|---|---|---|---:|---:|---|---|",
    ]
    for i, (score, corpus, row, tested, full, oracle) in enumerate(rows[: args.top], 1):
        lines.append(
            f"| {i} | `{row['name']}` | {row['category']} | {row['status']} | "
            f"{count(row['tests'])} | {corpus} | {'yes' if oracle else 'no'} | {row['owner'] or '-'} |"
        )
    lines += [
        "",
        f"Gap rows with corpus usage: {len(rows)}.",
        "",
        "## Oracle evidence",
        "",
        "- Event-command laws (`change_tune`, `change_vol`, `change_pan`, `fade_in`, `fade_out`):",
        "  probe `tools/kontakt-oracle/probes/event_bridge_laws.lua`, analysis",
        "  `tools/kontakt-oracle/analyze_event_laws.py`. Pending: the shared oracle lock queue",
        "  had not granted a session when this file was generated.",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} gap rows, top {min(args.top, len(rows))} listed")


if __name__ == "__main__":
    main()
