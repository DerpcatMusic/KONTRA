#!/usr/bin/env python3
"""Generate crates/sampler-core/src/dsp/machine_tables.rs from the Kontakt 8 PE.

Reads the S1200 mode-filter coefficient tables from .rdata (the render
FUN_140cdf460 selects them by filter mode 2..=5) and writes their binary32
bit patterns. Run from the repo root:

    python3 tools/re/gen_machine_tables.py /path/to/Kontakt8.exe

Constants that the decompile writes as immediates (the gains at +0x1fb8,
the anti-alias taps) are kept in machine.rs with their decompile addresses.
"""
import struct
import sys

import pefile

BASE = 0x140000000
# Per filter mode: 5-value section coefficients (DAT_144fd02f8 .. DAT_144fd03a0).
MODE_TABLES = {2: 0x144FD02F8, 3: 0x144FD0330, 4: 0x144FD0368, 5: 0x144FD03A0}
# Shared 5-value numerator table (DAT_144fd0310 is the mode-2 copy; all modes match).
NUMERATOR_TABLE = 0x144FD0310
# Stored gains (object +0x1fb8, written by the render per mode): immediates.
MODE_GAINS = {2: 0x3A150E48, 3: 0x3AB3A772, 4: 0x3B4886A5, 5: 0x3BAB2EB5}


def read_bits(pe, data, va, count):
    off = pe.get_offset_from_rva(va - BASE)
    return list(struct.unpack_from("<%dI" % count, data, off))


def main(path):
    pe = pefile.PE(path, fast_load=True)
    data = pe.__data__
    numerator = read_bits(pe, data, NUMERATOR_TABLE, 5)
    out = []
    out.append("//! Generated by tools/re/gen_machine_tables.py from Kontakt8.exe. Do not edit.")
    out.append("//! binary32 bit patterns; see dsp/machine.rs for the topology.")
    out.append("")
    out.append("/// S1200 numerator coefficients `[B0, B1, B2, B3, B4]` (DAT_144fd0310).")
    out.append("pub const S1200_NUMERATOR_BITS: [u32; 5] = [%s];" % ", ".join("0x%08x" % v for v in numerator))
    out.append("")
    out.append("/// S1200 filter-mode denominators `[A0..A4]` per stored mode (DAT_144fd02f8..).")
    out.append("pub const S1200_MODE_BITS: [(u8, [u32; 5], u32); 4] = [")
    for mode in sorted(MODE_TABLES):
        a = read_bits(pe, data, MODE_TABLES[mode], 5)
        out.append("    (%d, [%s], 0x%08x)," % (mode, ", ".join("0x%08x" % v for v in a), MODE_GAINS[mode]))
    out.append("];")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
